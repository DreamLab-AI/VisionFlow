#!/usr/bin/env python3
"""Component and path coverage of the diagram corpus, per repository.

For each repository a topic cites, list its top-level components (the first
one or two path segments that hold source: `crates/<name>`, `packages/<name>`,
`src/<name>`, or a top-level directory) and which topics cite at least one file
inside each. A component with tracked source files and no citing topic is a
coverage gap: no diagram describes it, so the audit has not checked it.

Usage: python3 -I component_coverage.py <diagrams-dir> <workspace-dir> [out.md]

Repositories are read at HEAD of their workspace checkout with `git ls-tree`;
the working tree is never read. RuView is skipped (excluded from the audit).
"""
import collections
import os
import re
import subprocess
import sys

SRC_EXT = re.compile(r"\.(rs|ts|tsx|js|mjs|cjs|py|go|nix|sh|gd|wgsl|cu|toml|sql)$")
NESTED = ("crates", "packages", "apps", "services", "src", "lib", "workers", "plugins")
EXCLUDED_REPOS = {"RuView"}


def topic_sources(diagrams):
    """Yield (topic-id, repo, repo-relative path) for every `sources:` entry."""
    for area in sorted(os.listdir(diagrams)):
        d = os.path.join(diagrams, area)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".md"):
                continue
            text = open(os.path.join(d, f)).read()
            m = re.match(r"---\n(.*?)\n---\n", text, re.S)
            if not m:
                continue
            fm = m.group(1)
            tid = re.search(r"^id:\s*(\S+)", fm, re.M)
            block = re.search(r"^sources:\s*\n((?:\s*-\s*.+\n?)+)", fm, re.M)
            if not tid or not block:
                continue
            for src in re.findall(r"^\s*-\s*(\S+)", block.group(1), re.M):
                if src.startswith("../"):
                    parts = src.split("/")
                    repo, rel = parts[1], "/".join(parts[2:])
                    # VisionClaw's agentbox submodule is the agentbox repository.
                    if repo == "project" and rel.startswith("agentbox/"):
                        repo, rel = "agentbox", rel[len("agentbox/"):]
                else:
                    repo, rel = "VisionFlow", src
                yield tid.group(1), repo, rel


def component_of(path):
    parts = path.split("/")
    if len(parts) > 2 and parts[0] in NESTED:
        return "/".join(parts[:2])
    return parts[0] if len(parts) > 1 else "(root)"


def tracked(repo_dir):
    r = subprocess.run(["git", "-C", repo_dir, "ls-tree", "-r", "--name-only", "HEAD"],
                       capture_output=True, text=True)
    return r.stdout.split("\n") if r.returncode == 0 else None


def main():
    diagrams, ws = sys.argv[1], sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else None
    cites = collections.defaultdict(lambda: collections.defaultdict(set))
    for tid, repo, rel in topic_sources(diagrams):
        cites[repo][component_of(rel)].add(tid.split(".")[0])
    lines = ["# Component coverage of the diagram corpus", "",
             "Generated by `scripts/estate-review-ledger/component_coverage.py` from topic "
             "`sources:` and each repository's tracked files at HEAD. A component is uncited "
             "when it holds source files and no topic names a file inside it.", ""]
    totals = []
    for repo in sorted(cites, key=str.lower):
        if repo in EXCLUDED_REPOS:
            continue
        repo_dir = os.path.join(ws, repo if repo != "VisionClaw" else "project")
        if repo == "project":
            repo_dir = os.path.join(ws, "project")
        files = tracked(repo_dir)
        if files is None:
            lines += ["## %s" % repo, "", "Checkout not readable; skipped.", ""]
            continue
        comp_files = collections.Counter(component_of(f) for f in files if SRC_EXT.search(f))
        cited = cites[repo]
        rows, gaps = [], []
        for comp, n in sorted(comp_files.items(), key=lambda x: -x[1]):
            topics = sorted(cited.get(comp, ()))
            (rows if topics else gaps).append((comp, n, topics))
        covered_files = sum(n for _, n, _ in rows)
        all_files = sum(comp_files.values())
        totals.append((repo, len(rows), len(rows) + len(gaps), covered_files, all_files))
        lines += ["## %s" % repo, "",
                  "%d of %d components cited; %d of %d source files are in a cited component." %
                  (len(rows), len(rows) + len(gaps), covered_files, all_files), ""]
        if gaps:
            lines += ["Uncited components (source files):", ""]
            lines += ["- `%s` (%d)" % (c, n) for c, n, _ in gaps[:40]]
            if len(gaps) > 40:
                lines.append("- … %d more" % (len(gaps) - 40))
            lines.append("")
    summary = ["| Repository | Components cited | Source files in cited components |",
               "|---|---|---|"]
    summary += ["| %s | %d/%d | %d/%d |" % t for t in totals]
    text = "\n".join(lines[:5] + summary + [""] + lines[5:]) + "\n"
    if out:
        open(out, "w").write(text)
    print("\n".join(summary))


if __name__ == "__main__":
    main()
